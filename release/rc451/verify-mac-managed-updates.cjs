'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict'),cp=require('node:child_process');
const stage=path.resolve(process.argv[2]),app=path.join(stage,'QCU助手.app'),kit=path.join(app,'Contents/Resources');
const proof=JSON.parse(fs.readFileSync(path.join(kit,'support/managed-updates.json'),'utf8'));
assert.equal(proof.customAsarSha256,'759bf095f7e4e6b97380f6103a9a6b8c34fc980c4b7b9b34bd1c1cf1f8ed0583');
assert.equal(proof.managedUpdates,true);
assert.equal(proof.minimumVersionPolicyUnchanged,true);
assert.equal(proof.securityFusesChanged,false);
assert.equal(proof.asarRepatched,false);
const main=path.join(stage,'patched-main.js');
assert.ok(fs.existsSync(main));
const verify=path.resolve(__dirname,'../../tools/teacher-branding/verify-managed-updates.cjs');
const r=cp.spawnSync(process.execPath,[verify,main],{encoding:'utf8'});
assert.equal(r.status,0,r.stderr||r.stdout);
const line=(r.stdout||'').trim().split('\n').find(s=>s.startsWith('QCU_MANAGED_UPDATES_VERIFIED:'));
assert.ok(line);
const report=JSON.parse(line.slice('QCU_MANAGED_UPDATES_VERIFIED:'.length));
assert.equal(report.manualAndAutomaticChecksBlocked,true);
assert.equal(report.directDownloadAndInstallBlocked,true);
assert.equal(report.ordinaryTimers,0);
console.log(JSON.stringify({passed:true,platform:'mac-arm64',asarRepatched:false,proofDigest:proof.customAsarSha256,backend:report,gui:false}));
